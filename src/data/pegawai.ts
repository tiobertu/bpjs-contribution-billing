export interface PegawaiRaw {
  no: number;
  nama: string;
  tanggalLahir: string; // yyyy-mm-dd
  nipb: string;
  cabang: string;
  tk: number;
  kes: number;
}

// Ubah dd-mm-yyyy menjadi yyyy-mm-dd
function toISODate(d: string): string {
  const parts = d.trim().split("-");
  if (parts.length !== 3) return "";
  const [dd, mm, yyyy] = parts;
  return `${yyyy}-${mm.padStart(2, "0")}-${dd.padStart(2, "0")}`;
}

export const dataPegawai: PegawaiRaw[] = RAW.trim()
  .split("\n")
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line, i) => {
    const [nama, tgl, nipb, cabang, tk, kes] = line.split("|");
    return {
      no: i + 1,
      nama: nama.trim(),
      tanggalLahir: toISODate(tgl),
      nipb: nipb.trim(),
      cabang: cabang.trim(),
      tk: Number(tk) || 0,
      kes: Number(kes) || 0,
    };
  });

// Daftar kantor cabang unik — Kantor Pusat selalu paling atas
export const daftarCabang: string[] = (() => {
  const set = Array.from(new Set(dataPegawai.map((p) => p.cabang)));
  const pusat = set.filter((n) => n.toLowerCase().includes("kantor pusat"));
  const lain = set
    .filter((n) => !n.toLowerCase().includes("kantor pusat"))
    .sort((a, b) => a.localeCompare(b, "id"));
  return [...pusat, ...lain];
})();

// Peta nama cabang -> id cabang
export const cabangIdMap: Record<string, string> = daftarCabang.reduce(
  (acc, nama, i) => {
    acc[nama] = "c" + (i + 1);
    return acc;
  },
  {} as Record<string, string>
);
